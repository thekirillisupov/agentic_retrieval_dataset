"""Every LLM prompt in the SID pipeline.

Each system prompt carries a ``[[SID:<tag>]]`` marker. It tells the offline mock
backend which shape to answer with, and makes it trivial to grep a trace for
"which call was this". Real models ignore it.
"""
from __future__ import annotations

from typing import Any

from .taxonomy import MECHANICS

TAG = "[[SID:%s]]"


def _chunks_block(chunks: list[tuple[str, str]]) -> str:
    return "\n\n".join(f"[CHUNK {cid}]\n{text}" for cid, text in chunks)


def _facts_block(facts: list[dict[str, Any]]) -> str:
    return "\n".join(
        f"- [{f['fact_id']} @ {f['chunk_id']}] {f['fact_normalized']}"
        f"\n  цитата: «{f['verbatim_span']}»"
        for f in facts)


# --------------------------------------------------------------------------- #
# S3 — fact extraction
# --------------------------------------------------------------------------- #
FACTS_SYS = (TAG % "facts") + """
Ты извлекаешь атомарные факты из фрагмента документа для построения поисковых задач.

Правила:
- Атомарный факт = одно утверждение, которое нельзя разбить дальше без потери смысла.
- verbatim_span — ТОЧНАЯ подстрока из фрагмента (копируй символ в символ), подтверждающая факт.
- fact_normalized — тот же факт своими словами, самодостаточно (без «в тексте», «здесь»).
- discriminating_attributes — атрибуты, отличающие факт от похожих: даты, суммы,
  номера, версии, названия. Формат "тип:значение", например "date:2015", "amount:4 млрд".
- Не выдумывай ничего, чего нет во фрагменте.

Ответ — строго JSON: {"facts": [{"verbatim_span": "...", "fact_normalized": "...",
"entities": ["..."], "discriminating_attributes": ["date:...", "org:..."]}]}
"""


def facts_user(chunk_id: str, text: str, max_facts: int) -> str:
    return (f"Фрагмент [CHUNK {chunk_id}]:\n{text}\n\n"
            f"Извлеки до {max_facts} самых информативных атомарных фактов.")


# --------------------------------------------------------------------------- #
# S3 — composition
# --------------------------------------------------------------------------- #
COMPOSE_SYS = (TAG % "compose") + """
Ты составляешь поисковый вопрос для обучения агента-ретривера.

Жёсткие требования:
1. Ответ выводится ТОЛЬКО при совместном использовании фактов минимум из ДВУХ разных фрагментов.
2. Вопрос самодостаточен: никаких «в тексте», «согласно документу», «в этом фрагменте».
3. Вопрос НЕ раскрывает ответ и НЕ называет промежуточные сущности, которые агент
   обязан найти сам.
4. Формулируй своими словами: не копируй редкие фразы из фрагментов дословно —
   иначе задача решается тривиальным лексическим совпадением.
5. Ответ короткий и фактический.
6. Пиши на русском языке, как пишет реальный пользователь, а не как экзаменатор.

Ответ — строго JSON: {"question": "...", "answer": "...",
"used_fact_ids": ["f_..."], "reasoning": "..."}
"""


def compose_user(cell, facts: list[dict[str, Any]], feedback: str = "") -> str:
    mech = MECHANICS[cell.mechanic]
    neg = ("\nДополнительно: вопрос должен содержать ОТРИЦАНИЕ или исключение "
           "(«кроме», «не относящийся к», «за исключением») как содержательное "
           "ограничение, а не как украшение." if cell.has_negation else "")
    fb = f"\n\nПРЕДЫДУЩАЯ ПОПЫТКА ОТКЛОНЕНА. Причина: {feedback}\nИсправь именно это." if feedback else ""
    return f"""Механика поиска: {cell.mechanic}
Что она означает: {mech['plan']}
Как это должно проявиться в вопросе: {mech['compose']}
Подтип (используй именно его): {cell.submechanic}{neg}

Доступные факты:
{_facts_block(facts)}

Составь ОДИН вопрос указанной механики и подтипа, ответ на него, и перечисли
fact_id всех фактов, действительно необходимых для ответа (минимум два фрагмента).{fb}"""


# --------------------------------------------------------------------------- #
# S4 — G_SOLVE critic
# --------------------------------------------------------------------------- #
SOLVE_SYS = (TAG % "solve") + """
Ты — строгий критик поисковых задач. Тебе дан вопрос, предложенный ответ и полный
набор фактов (gold-set). Проверь:

- solvable: выводится ли ответ ОДНОЗНАЧНО из этих фактов (без догадок и внешних знаний);
- answer_correct: совпадает ли предложенный ответ с тем, что следует из фактов;
- leaks_answer: содержится ли ответ прямо в тексте вопроса;
- leaks_intermediate: названы ли в вопросе промежуточные сущности, которые агент
  должен был найти сам;
- standalone: понятен ли вопрос без доступа к исходным фрагментам;
- needs_multiple_chunks: действительно ли нужны факты минимум из двух разных фрагментов.

Ответ — строго JSON: {"solvable": bool, "answer_correct": bool, "leaks_answer": bool,
"leaks_intermediate": bool, "standalone": bool, "needs_multiple_chunks": bool,
"reason": "коротко"}
"""

SOLVE_DEVIL_SYS = (TAG % "solve_devil") + """
Ты — адвокат дьявола. Твоя задача — обосновать, что вопрос НЕ решается однозначно
из предложенного набора фактов: найти пропущенное звено, неоднозначность или
подмену. Если честных возражений нет — признай это.

Ответ — строго JSON: {"solvable": bool, "reason": "коротко"}
"""


def solve_user(question: str, answer: str, facts: list[dict[str, Any]]) -> str:
    return (f"ВОПРОС: {question}\n\nПРЕДЛОЖЕННЫЙ ОТВЕТ: {answer}\n\n"
            f"GOLD-ФАКТЫ:\n{_facts_block(facts)}")


# --------------------------------------------------------------------------- #
# S5 — G_REP entailment
# --------------------------------------------------------------------------- #
ENTAIL_SYS = (TAG % "entail") + """
Проверь, утверждает ли фрагмент данный факт. «Утверждает» = факт прямо следует из
фрагмента, не требуя внешних знаний. Похожая тема — недостаточно.

Ответ — строго JSON: {"states_fact": bool, "reason": "коротко"}
"""


def entail_user(fact: str, chunk_id: str, text: str) -> str:
    return f"ФАКТ: {fact}\n\n[CHUNK {chunk_id}]\n{text}"


# --------------------------------------------------------------------------- #
# S6 — distractors
# --------------------------------------------------------------------------- #
PERTURB_SYS = (TAG % "perturb") + """
Ты строишь near-miss дистрактор для поисковой задачи: документ, который выглядит
как подходящий ответ, но им не является.

Правила:
- Возьми исходный фрагмент и измени РОВНО ОДИН различающий атрибут (дату, сумму,
  номер, версию, место) так, чтобы документ перестал отвечать на вопрос.
- Стиль, регистр и структуру исходного текста сохрани полностью.
- Ответ на вопрос НЕ должен выводиться из результата ни прямо, ни косвенно.
- Не добавляй пометок о том, что текст изменён.

Ответ — строго JSON: {"text": "...", "perturbed_attribute": "date:2019 -> date:2021",
"distractor_type": "near_duplicate|partial_answer"}
"""


def perturb_user(question: str, answer: str, source_text: str,
                 attributes: list[str]) -> str:
    attrs = ", ".join(attributes) or "(не заданы — выбери сам)"
    return (f"ВОПРОС ЗАДАЧИ: {question}\nОТВЕТ ЗАДАЧИ (его нельзя раскрывать): {answer}\n"
            f"РАЗЛИЧАЮЩИЕ АТРИБУТЫ gold-фактов: {attrs}\n\n"
            f"ИСХОДНЫЙ ФРАГМЕНТ:\n{source_text}")


TRANSPLANT_SYS = (TAG % "transplant") + """
Ты переносишь реальный фрагмент документа в тематическую окрестность другой задачи.

Правила:
- Замени поверхностные сущности (имена, организации, локации, коды, продукты) на
  заданные, оставив весь остальной текст без изменений.
- Не переноси и не добавляй факты, отвечающие на вопрос задачи.
- Стиль и структура исходного текста сохраняются полностью.

Ответ — строго JSON: {"text": "...", "distractor_type": "topical_lure|homonym"}
"""


def transplant_user(question: str, answer: str, source_text: str,
                    entities: list[str]) -> str:
    ents = ", ".join(entities) or "(нет)"
    return (f"ВОПРОС ЗАДАЧИ (ответ на него текст давать НЕ должен): {question}\n"
            f"ОТВЕТ ЗАДАЧИ: {answer}\n"
            f"СУЩНОСТИ ДЛЯ ПОДСТАНОВКИ: {ents}\n\n"
            f"ИСХОДНЫЙ ФРАГМЕНТ:\n{source_text}")


GENERATE_SYS = (TAG % "generate_distractor") + """
Ты пишешь документ-дистрактор в стиле корпуса: та же тема и терминология, что у
образца, но ответа на вопрос в нём нет.

Правила:
- Повтори регистр, длину и структуру образца.
- Тема близка к вопросу, но ни один требуемый факт не воспроизводится.
- Никаких пометок о синтетичности.

Ответ — строго JSON: {"text": "...", "distractor_type": "topical_lure|partial_answer"}
"""


def generate_distractor_user(question: str, answer: str, template_text: str) -> str:
    return (f"ВОПРОС ЗАДАЧИ (ответа быть не должно): {question}\n"
            f"ОТВЕТ ЗАДАЧИ: {answer}\n\nОБРАЗЕЦ СТИЛЯ:\n{template_text}")


DISTRACTOR_CHECK_SYS = (TAG % "distractor_check") + """
Проверь документ-кандидат в дистракторы. Он НЕ годится, если:
- содержит ответ на вопрос в любой форме;
- является валидным альтернативным путём к ответу (даёт достаточные сведения).

Ответ — строго JSON: {"contains_answer": bool, "valid_alternative_path": bool,
"reason": "коротко"}
"""


def distractor_check_user(question: str, answer: str, text: str) -> str:
    return f"ВОПРОС: {question}\nОТВЕТ: {answer}\n\nКАНДИДАТ:\n{text}"


# --------------------------------------------------------------------------- #
# S7 — isolation
# --------------------------------------------------------------------------- #
ISOLATION_SYS = (TAG % "isolation") + """
Тебе даны вопрос, его ответ и фрагменты, которые НЕ размечены как gold, но
возвращаются поиском по этому вопросу. Определи, какие из них позволяют получить
тот же ответ в обход размеченной цепочки (сами по себе или вместе).

Ответ — строго JSON: {"alternative_path_chunk_ids": ["..."], "reason": "коротко"}
"""


def isolation_user(question: str, answer: str, chunks: list[tuple[str, str]]) -> str:
    return (f"ВОПРОС: {question}\nОТВЕТ: {answer}\n\n"
            f"НЕРАЗМЕЧЕННЫЕ ФРАГМЕНТЫ ИЗ ВЫДАЧИ:\n{_chunks_block(chunks)}")
